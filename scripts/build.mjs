// Build pipeline. Four steps, each feeding the next:
//   1. player  : src/player/main.ts + styles.css  -> src/generated/player-assets.ts (two string constants)
//   2. errors  : the issue catalogs               -> plugin/skills/learning-tool/references/errors.md
//   3. guide   : plugin/skills/learning-tool/*.md -> src/generated/guide.ts (the skill text, served by get_guide)
//   4. server  : src/server/main.ts               -> plugin/server/learning-tool.mjs (one self-contained file)
//
// Usage: node scripts/build.mjs [--only=player|errors|guide|server]
import { build } from 'esbuild';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) => path.join(root, ...p);
const only = process.argv.find((a) => a.startsWith('--only='))?.slice('--only='.length);
const wants = (step) => !only || only === step;

const HEADER = '// GENERATED by scripts/build.mjs. Do not edit.\n';

async function writeIfChanged(file, content) {
  await mkdir(path.dirname(file), { recursive: true });
  if (existsSync(file) && (await readFile(file, 'utf8')) === content) return false;
  await writeFile(file, content);
  return true;
}

async function buildPlayer() {
  const js = await build({
    entryPoints: [rel('src/player/main.ts')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2020', 'safari15'],
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });
  const css = await build({
    entryPoints: [rel('src/player/styles.css')],
    bundle: true,
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });
  const jsText = js.outputFiles[0].text;
  const cssText = css.outputFiles[0].text;
  await writeIfChanged(
    rel('src/generated/player-assets.ts'),
    `${HEADER}export const PLAYER_JS: string = ${JSON.stringify(jsText)};\n` +
      `export const PLAYER_CSS: string = ${JSON.stringify(cssText)};\n`,
  );
  return { js: jsText.length, css: cssText.length };
}

function stripFrontmatter(md) {
  if (!md.startsWith('---')) return md;
  const end = md.indexOf('\n---', 3);
  return end === -1 ? md : md.slice(md.indexOf('\n', end + 1) + 1).replace(/^\n+/, '');
}

async function buildGuide() {
  const skillDir = rel('plugin/skills/learning-tool');
  const sections = {};
  if (existsSync(path.join(skillDir, 'SKILL.md'))) {
    sections.overview = stripFrontmatter(await readFile(path.join(skillDir, 'SKILL.md'), 'utf8'));
  }
  const refDir = path.join(skillDir, 'references');
  if (existsSync(refDir)) {
    for (const name of (await readdir(refDir)).filter((n) => n.endsWith('.md')).sort()) {
      sections[name.replace(/\.md$/, '')] = await readFile(path.join(refDir, name), 'utf8');
    }
  }
  await writeIfChanged(
    rel('src/generated/guide.ts'),
    `${HEADER}export const GUIDE: Record<string, string> = ${JSON.stringify(sections, null, 2)};\n`,
  );
  return Object.keys(sections);
}

// The error reference is rendered from the same catalogs the validator and server report from, so
// the skill can never describe a code that does not exist or miss one that does.
async function buildErrors() {
  const entry = [
    `import { issueCatalogMarkdown } from ${JSON.stringify(rel('src/core/issues.ts'))};`,
    `import { serverIssuesMarkdown } from ${JSON.stringify(rel('src/server/issues.ts'))};`,
    'export const markdown = [issueCatalogMarkdown().trimEnd(), serverIssuesMarkdown().trimEnd()].join(String.fromCharCode(10, 10)) + String.fromCharCode(10);',
  ].join('\n');
  const out = await build({
    stdin: { contents: entry, resolveDir: root, loader: 'ts' },
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    write: false,
    logLevel: 'warning',
  });
  const url = `data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`;
  const { markdown } = await import(url);
  await writeIfChanged(rel('plugin/skills/learning-tool/references/errors.md'), markdown);
  return markdown.length;
}

async function buildVersion() {
  const pkg = JSON.parse(await readFile(rel('package.json'), 'utf8'));
  await writeIfChanged(rel('src/generated/version.ts'), `${HEADER}export const VERSION: string = ${JSON.stringify(pkg.version)};\n`);
  return pkg.version;
}

async function buildServer() {
  const out = rel('plugin/server/learning-tool.mjs');
  const result = await build({
    entryPoints: [rel('src/server/main.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    outfile: out,
    banner: {
      // A bundled ESM file has no require(); some dependencies still expect one.
      js: "#!/usr/bin/env node\nimport { createRequire as __ltCreateRequire } from 'node:module';\nconst require = __ltCreateRequire(import.meta.url);",
    },
    legalComments: 'none',
    metafile: true,
    logLevel: 'warning',
  });
  return Object.values(result.metafile.outputs)[0].bytes;
}

const report = {};
report.version = await buildVersion();
if (wants('player')) report.player = await buildPlayer();
if (wants('errors')) report.errorsChars = await buildErrors();
if (wants('guide')) report.guide = await buildGuide();
if (wants('server')) report.serverBytes = await buildServer();
console.error(`build ok ${JSON.stringify(report)}`);
